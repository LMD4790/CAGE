#!/usr/bin/env python3
"""Verify the documented training and prediction workflow on synthetic inputs."""

import argparse
from datetime import datetime, timezone
import importlib.metadata
import json
import os
from pathlib import Path
import platform
import subprocess
import sys
import time

import numpy as np
from sklearn.metrics import accuracy_score, f1_score


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--device", default="cpu")
    parser.add_argument("--model-name", help="Optional full-size CodeBERT checkpoint to test")
    args = parser.parse_args()
    output = args.output_dir.resolve()
    if output.exists() and any(output.iterdir()):
        parser.error("output-dir must be empty")
    output.mkdir(parents=True, exist_ok=True)
    root = Path(__file__).resolve().parents[1]
    environment = dict(os.environ)
    environment.setdefault("OMP_NUM_THREADS", "2")
    environment.setdefault("MKL_NUM_THREADS", "2")
    environment.setdefault("PYTEST_DISABLE_PLUGIN_AUTOLOAD", "1")
    report = {
        "status": "running", "started_utc": datetime.now(timezone.utc).isoformat(),
        "platform": platform.platform(), "python": platform.python_version(),
        "device": args.device, "steps": [],
        "data": "synthetic examples generated by create_toy_project.py",
        "versions": {p: importlib.metadata.version(p) for p in (
            "torch", "transformers", "numpy", "scikit-learn", "lightgbm",
            "tree-sitter", "tree-sitter-languages", "rapidfuzz", "pytest",
        )},
    }

    def save():
        (output / "report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

    def run(name, arguments):
        started = time.monotonic()
        command = [sys.executable, *map(str, arguments)]
        with (output / (name + ".log")).open("w", encoding="utf-8") as handle:
            result = subprocess.run(command, cwd=root, env=environment, stdout=handle, stderr=subprocess.STDOUT)
        report["steps"].append({
            "name": name, "command": command, "exit_code": result.returncode,
            "seconds": round(time.monotonic() - started, 3),
        })
        save()
        if result.returncode:
            raise RuntimeError(f"{name} failed; see {name}.log")
        print(f"{name}: passed", flush=True)

    def validate_predictions(model_dir, predictions_path):
        original = [json.loads(line) for line in (model_dir / "test_predictions.jsonl").read_text().splitlines()]
        repeated = [json.loads(line) for line in predictions_path.read_text().splitlines()]
        if len(original) != len(repeated) or len(original) != 6:
            raise AssertionError("Prediction count mismatch")
        for a, b in zip(original, repeated):
            assert a["id"] == b["id"] and a["prediction"] == b["prediction"]
            np.testing.assert_allclose(a["probabilities"], b["probabilities"], atol=1e-6)
        actual = [row["label"] for row in original]
        predicted = [row["prediction"] for row in original]
        stored = json.loads((model_dir / "test_metrics.json").read_text())
        np.testing.assert_allclose(stored["test"]["accuracy"], accuracy_score(actual, predicted))
        np.testing.assert_allclose(stored["test"]["macro_f1"], f1_score(actual, predicted, labels=[0, 1], average="macro", zero_division=0))
        history = json.loads((model_dir / "history.json").read_text())
        selected = max(history, key=lambda row: row["validation"]["macro_f1"])["epoch"]
        assert stored["best_epoch"] == selected

    try:
        run("unit_tests", ["-m", "pytest", "-q"])
        run("smoke", ["examples/smoke_test.py", "--device", args.device])
        toy = output / "toy"
        run("create_examples", ["examples/create_toy_project.py", "--output-dir", toy])
        prepared = toy / "prepared"
        common = [
            "--train-jsonl", prepared / "train.jsonl",
            "--val-jsonl", prepared / "val.jsonl",
            "--test-jsonl", prepared / "test.jsonl",
        ]
        run("prepare_support", [
            "scripts/prepare_support.py",
            "--train-jsonl", toy / "raw/train.jsonl", "--val-jsonl", toy / "raw/val.jsonl",
            "--test-jsonl", toy / "raw/test.jsonl", "--num-classes", "2",
            "--output-dir", prepared, "--n-jobs", "2",
        ])
        amp = ["--fp16"] if args.device.startswith("cuda") else []
        run("tiny_training", [
            "train.py", *common, "--model-name", toy / "encoder",
            "--output-dir", toy / "model", "--epochs", "2", "--batch-size", "2",
            "--max-length", "64", "--warmup-steps", "0", "--device", args.device, *amp,
        ])
        run("tiny_prediction", [
            "predict.py", "--model-dir", toy / "model", "--input-jsonl", toy / "raw/test.jsonl",
            "--support-model", prepared / "support_model.joblib", "--batch-size", "2",
            "--output-jsonl", toy / "predictions.jsonl", "--device", args.device,
        ])
        validate_predictions(toy / "model", toy / "predictions.jsonl")
        report["tiny_checkpoint_and_metrics_verified"] = True
        if args.model_name:
            run("pretrained_smoke", [
                "examples/pretrained_smoke.py", "--model-name", args.model_name,
                "--device", args.device,
            ])
            run("pretrained_training", [
                "train.py", *common, "--model-name", args.model_name,
                "--output-dir", toy / "pretrained_model", "--epochs", "1", "--batch-size", "1",
                "--max-length", "512", "--warmup-steps", "0", "--device", args.device, *amp,
            ])
            run("pretrained_prediction", [
                "predict.py", "--model-dir", toy / "pretrained_model",
                "--input-jsonl", toy / "raw/test.jsonl",
                "--support-model", prepared / "support_model.joblib",
                "--output-jsonl", toy / "pretrained_predictions.jsonl",
                "--batch-size", "1", "--device", args.device,
            ])
            validate_predictions(toy / "pretrained_model", toy / "pretrained_predictions.jsonl")
            report["pretrained_checkpoint_and_metrics_verified"] = True
        report["status"] = "passed"
    except Exception as error:
        report["status"] = "failed"
        report["error"] = str(error)
        raise
    finally:
        report["finished_utc"] = datetime.now(timezone.utc).isoformat()
        save()
    print(f"Verification passed. Report: {output / 'report.json'}")


if __name__ == "__main__":
    main()
